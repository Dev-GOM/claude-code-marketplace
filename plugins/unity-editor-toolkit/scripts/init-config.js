#!/usr/bin/env node

/**
 * Initialize Unity WebSocket project configuration at session start.
 * This script is called by the SessionStart hook to automatically register
 * the current Unity project in the shared configuration file.
 *
 * Only runs on 'startup' source - skips 'resume', 'clear', 'compact' events.
 */

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');
const { createLogger } = require('./logger');
const hookUtils = require('./shared/hook-utils');

// Get hookInput early to determine project name (with safe parsing)
let hookInput = null;
const tempLogger = { warn: console.warn, log: console.log, error: console.error };
if (process.argv[2]) {
  hookInput = hookUtils.safeParseJSON(process.argv[2], tempLogger);
}

// Get project name early for logging
let projectName = null;
if (process.env.CLAUDE_PROJECT_DIR) {
  projectName = path.basename(process.env.CLAUDE_PROJECT_DIR);
} else if (hookInput && hookInput.cwd) {
  projectName = path.basename(hookInput.cwd);
}

// Create logger instance with project name
const logger = createLogger('init-log.txt', 'Unity WebSocket Initialization Log', projectName || 'unknown');

/**
 * Check if a port is available
 */
async function isPortAvailable(port) {
  return new Promise((resolve) => {
    const server = require('net').createServer();

    server.once('error', () => {
      resolve(false);
    });

    server.once('listening', () => {
      server.close();
      resolve(true);
    });

    server.listen(port, '127.0.0.1');
  });
}

/**
 * Find available port in range 9300-9400
 */
async function findAvailablePort(usedPorts, basePort = 9300) {
  let port = basePort;

  while (usedPorts.includes(port) || !(await isPortAvailable(port))) {
    port++;
    if (port > 9400) {
      throw new Error('No available port found in range 9300-9400');
    }
  }

  return port;
}

/**
 * Check if Unity project (has Assets and ProjectSettings folders)
 */
function isUnityProject(projectRoot) {
  const assetsDir = path.join(projectRoot, 'Assets');
  const projectSettingsDir = path.join(projectRoot, 'ProjectSettings');
  return fs.existsSync(assetsDir) && fs.existsSync(projectSettingsDir);
}

/**
 * Create .unity-websocket output directory in project root
 */
function createOutputDirectory(projectRoot) {
  const outputDir = path.join(projectRoot, '.unity-websocket');

  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  const gitignorePath = path.join(outputDir, '.gitignore');
  if (!fs.existsSync(gitignorePath)) {
    const gitignoreContent = `# Unity WebSocket generated files
*
`;
    fs.writeFileSync(gitignorePath, gitignoreContent, 'utf-8');
  }
}

/**
 * Create CLI wrapper script for easy command execution
 */
function createWrapperScript(projectRoot) {
  const wrapperPath = path.join(projectRoot, '.unity-websocket', 'uw.js');

  const wrapperContent = `#!/usr/bin/env node

/**
 * Unity WebSocket CLI Wrapper
 *
 * This wrapper script forwards all arguments to the local CLI installation.
 * Auto-generated by unity-websocket-skill SessionStart hook.
 *
 * Usage: node .unity-websocket/uw.js <command> [options]
 * Example: node .unity-websocket/uw.js hierarchy
 */

const path = require('path');

// Set CLAUDE_PROJECT_DIR to project root (parent of .unity-websocket)
process.env.CLAUDE_PROJECT_DIR = path.resolve(__dirname, '..');

// Get the actual CLI path
const cliPath = path.join(__dirname, 'skills', 'scripts', 'dist', 'cli', 'cli.js');

// Forward to the actual CLI
require(cliPath);
`;

  fs.writeFileSync(wrapperPath, wrapperContent, 'utf-8');
  logger.log('Created CLI wrapper: .unity-websocket/uw.js');
}

/**
 * Initialize local scripts in project .unity-websocket directory
 */
async function initializeLocalScripts(projectRoot) {
  const localSkillsPath = path.join(projectRoot, '.unity-websocket/skills/scripts');
  const pluginRoot = process.env.CLAUDE_PLUGIN_ROOT;

  if (!pluginRoot) {
    logger.error('CLAUDE_PLUGIN_ROOT not available, skipping local scripts initialization');
    return;
  }

  const pluginScriptsPath = path.join(pluginRoot, 'skills/scripts');
  const pluginPackageJson = path.join(pluginScriptsPath, 'package.json');

  if (!fs.existsSync(pluginPackageJson)) {
    logger.error('Plugin scripts not found at: ' + pluginScriptsPath);
    return;
  }

  const pluginVersion = JSON.parse(fs.readFileSync(pluginPackageJson, 'utf-8')).version;
  logger.log('Plugin scripts version: ' + pluginVersion);

  let needsUpdate = false;

  if (fs.existsSync(localSkillsPath)) {
    const localPackageJson = path.join(localSkillsPath, 'package.json');
    if (fs.existsSync(localPackageJson)) {
      const localVersion = JSON.parse(fs.readFileSync(localPackageJson, 'utf-8')).version;
      logger.log('Local scripts version: ' + localVersion);
      needsUpdate = pluginVersion !== localVersion;
    } else {
      needsUpdate = true;
    }
  } else {
    logger.log('Local scripts not found, initializing...');
    needsUpdate = true;
  }

  if (!needsUpdate) {
    logger.log('✅ Local scripts up-to-date (v' + pluginVersion + ')');
    return;
  }

  logger.log('Updating local scripts to v' + pluginVersion + '...');

  // STEP 1: Remove entire skills folder
  logger.log('[STEP 1] Removing .unity-websocket/skills folder...');
  const skillsDir = path.join(projectRoot, '.unity-websocket/skills');
  if (fs.existsSync(skillsDir)) {
    try {
      fs.rmSync(skillsDir, { recursive: true, force: true, maxRetries: 10, retryDelay: 500 });
      logger.log('✓ Skills folder removed');
    } catch (error) {
      logger.error('Failed to remove skills folder: ' + error.message);
      throw error;
    }
  }

  // STEP 2: Create fresh directory and copy files
  logger.log('[STEP 2] Creating directory structure...');
  fs.mkdirSync(localSkillsPath, { recursive: true });

  logger.log('[STEP 2] Copying source files...');
  fs.cpSync(path.join(pluginScriptsPath, 'src'), path.join(localSkillsPath, 'src'), { recursive: true });
  fs.copyFileSync(path.join(pluginScriptsPath, 'package.json'), path.join(localSkillsPath, 'package.json'));
  fs.copyFileSync(path.join(pluginScriptsPath, 'tsconfig.json'), path.join(localSkillsPath, 'tsconfig.json'));

  // STEP 3: Install dependencies and build
  logger.log('[STEP 3] Installing dependencies...');
  try {
    // Validate npm execution path (security: prevent command injection)
    const safePath = hookUtils.validateNpmPath(localSkillsPath, projectRoot, logger);
    const cleanEnv = hookUtils.getCleanNpmEnv();

    execSync('npm install', {
      cwd: safePath,
      stdio: 'inherit',
      env: cleanEnv,
    });
    logger.log('✓ Dependencies installed');
  } catch (error) {
    logger.error('npm install failed: ' + error.message);
    throw error;
  }

  logger.log('[STEP 3] Building scripts...');
  try {
    const safePath = hookUtils.validateNpmPath(localSkillsPath, projectRoot, logger);
    const cleanEnv = hookUtils.getCleanNpmEnv();

    execSync('npm run build', {
      cwd: safePath,
      stdio: 'inherit',
      env: cleanEnv,
    });
    logger.log('✓ Build completed');
  } catch (error) {
    logger.error('npm run build failed: ' + error.message);
    throw error;
  }

  logger.log('✅ Local scripts initialized successfully (v' + pluginVersion + ')');
}

/**
 * Initialize project configuration
 */
async function initializeProject(hookInput) {
  logger.log('Unity WebSocket: Starting initialization...');

  const projectRoot = hookUtils.getProjectRoot(hookInput, logger);
  const projectName = hookUtils.getProjectName(projectRoot);

  logger.log('Unity WebSocket: Project: ' + projectName);
  logger.log('Unity WebSocket: Root: ' + projectRoot);

  // Check if Unity project
  if (!isUnityProject(projectRoot)) {
    logger.warn('⚠️  Not a Unity project (missing Assets or ProjectSettings folder)');
    logger.warn('Unity WebSocket Skill works best with Unity projects');
  }

  // Always ensure output directory exists
  createOutputDirectory(projectRoot);

  // Initialize local scripts
  await initializeLocalScripts(projectRoot);

  // Create CLI wrapper
  createWrapperScript(projectRoot);

  // Load and update shared config
  const sharedConfig = hookUtils.loadSharedConfig(logger);
  const normalizedProjectRoot = path.normalize(projectRoot);

  // Check if project exists
  const existingEntry = Object.entries(sharedConfig.projects).find(
    ([_, config]) => path.normalize(config.rootPath) === normalizedProjectRoot
  );

  if (existingEntry) {
    const [existingName, config] = existingEntry;

    if (existingName !== projectName) {
      delete sharedConfig.projects[existingName];
      sharedConfig.projects[projectName] = config;
      hookUtils.saveSharedConfig(sharedConfig, logger);
      logger.log(`✅ Unity WebSocket: Updated project name: ${existingName} → ${projectName}`);
    } else {
      config.lastUsed = hookUtils.getLocalTimestamp();
      hookUtils.saveSharedConfig(sharedConfig, logger);
      logger.log(`✅ Unity WebSocket: Project "${projectName}" ready (Port: ${config.port})`);
    }

    return;
  }

  // Create new project config
  const basePort = parseInt(process.env.UNITY_WS_PORT || '9300');
  const usedPorts = Object.values(sharedConfig.projects).map(p => p.port);
  const port = await findAvailablePort(usedPorts, basePort);

  const projectConfig = {
    rootPath: normalizedProjectRoot,
    port: port,
    outputDir: '.unity-websocket',
    lastUsed: hookUtils.getLocalTimestamp(),
    autoCleanup: false
  };

  sharedConfig.projects[projectName] = projectConfig;
  hookUtils.saveSharedConfig(sharedConfig, logger);

  logger.log(`✅ Unity WebSocket: Registered project "${projectName}"`);
  logger.log(`   Port: ${port}`);
  logger.log(`   Output: ${projectConfig.outputDir}`);
}


// Main execution
(async () => {
  let lockFile = null;

  const cleanup = (signal) => {
    logger.log('Received ' + signal + ', cleaning up...');
    if (lockFile) {
      hookUtils.releaseLock(lockFile, logger);
    }
    logger.close();
    process.exit(1);
  };

  process.on('SIGINT', () => cleanup('SIGINT'));
  process.on('SIGTERM', () => cleanup('SIGTERM'));

  if (process.platform !== 'win32') {
    process.on('SIGHUP', () => cleanup('SIGHUP'));
  }

  try {
    const hookInput = await hookUtils.readHookInput();

    logger.log('Hook input: ' + JSON.stringify(hookInput));
    logger.log('CLAUDE_PROJECT_DIR env: ' + (process.env.CLAUDE_PROJECT_DIR || 'NOT SET'));

    // Skip clear and compact events
    if (hookInput.source === 'clear' || hookInput.source === 'compact') {
      logger.log('Skipping event: ' + hookInput.source);
      logger.close();
      process.exit(0);
    }

    const projectRoot = hookUtils.getProjectRoot(hookInput, logger);
    lockFile = await hookUtils.acquireLock(projectRoot, '.init.lock', logger);

    await initializeProject(hookInput);

    logger.close();
    hookUtils.releaseLock(lockFile, logger);
    process.exit(0);
  } catch (error) {
    logger.error('Error initializing Unity WebSocket: ' + error.message);
    logger.error('Stack: ' + error.stack);
    logger.close();
    if (lockFile) hookUtils.releaseLock(lockFile, logger);
    process.exit(1);
  }
})();
